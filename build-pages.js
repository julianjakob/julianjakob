#!/usr/bin/env node
/**
 * build-pages.js
 *
 * GitHub Pages serves /about from about.html — without these files every
 * sub-page answered with HTTP 404 and only JavaScript rescued the visitor,
 * so search engines never indexed them.
 *
 * Creates one HTML file per page (about.html, process.html, …) as a copy of
 * index.html whose <head> carries that page's title, description and
 * canonical URL. Titles and descriptions come from the data-title-en and
 * data-description attributes on each <main id="page-…"> in index.html.
 * Also rewrites sitemap.xml, and stamps style.css / script.js with a fingerprint of
 * their contents (style.css?v=…): when a file changes, its address changes, so no
 * browser can mix a new page with an old cached stylesheet or script.
 *
 * Ausführen: node build-pages.js
 * (nach jeder Änderung an index.html, style.css oder script.js ausführen, dann committen)
 */

const fs = require("fs");
const crypto = require("crypto");

const BASE = "https://julianjakob.at";

// Cache-busting: /style.css?v=<hash>, /script.js?v=<hash> (index.html is updated in place)
const fingerprint = (file) => crypto.createHash("sha1").update(fs.readFileSync(file)).digest("hex").slice(0, 10);
let stamped = fs.readFileSync("index.html", "utf8");
for (const file of ["style.css", "script.js"]) {
  stamped = stamped.replace(new RegExp(`/${file.replace(".", "\\.")}(\\?v=[0-9a-f]+)?"`, "g"), `/${file}?v=${fingerprint(file)}"`);
}
fs.writeFileSync("index.html", stamped);
const source = stamped;

const decode = (s) => s
  .replace(/&quot;/g, '"').replace(/&#x27;|&#39;/g, "'")
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
const encode = (s) => s
  .replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function attr(tag, name) {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? decode(m[1]) : null;
}

const pages = [...source.matchAll(/<main id="page-([a-z]+)"[^>]*>/g)].map((m) => ({
  id:          m[1],
  title:       attr(m[0], "data-title-en"),
  description: attr(m[0], "data-description"),
}));

function setHead(html, page, url) {
  const replacements = [
    [/<title>[^<]*<\/title>/,                                   `<title>${encode(page.title)}</title>`],
    [/<meta name="description" content="[^"]*">/,               `<meta name="description" content="${encode(page.description)}">`],
    [/<link rel="canonical" href="[^"]*">/,                     `<link rel="canonical" href="${url}">`],
    [/<meta property="og:url" content="[^"]*">/,                `<meta property="og:url" content="${url}">`],
    [/<meta property="og:title" content="[^"]*">/,              `<meta property="og:title" content="${encode(page.title)}">`],
    [/<meta property="og:description" content="[^"]*">/,        `<meta property="og:description" content="${encode(page.description)}">`],
    [/<meta name="twitter:title" content="[^"]*">/,             `<meta name="twitter:title" content="${encode(page.title)}">`],
    [/<meta name="twitter:description" content="[^"]*">/,      `<meta name="twitter:description" content="${encode(page.description)}">`],
  ];
  for (const [re, value] of replacements) {
    if (!re.test(html)) throw new Error(`index.html is missing ${re}`);
    html = html.replace(re, value);
  }
  return html;
}

const today = new Date().toISOString().slice(0, 10);
const sitemapEntries = [];

for (const page of pages) {
  if (!page.title || !page.description) {
    console.warn(`✗ page-${page.id}: missing data-title-en or data-description`);
    continue;
  }
  const url = page.id === "home" ? `${BASE}/` : `${BASE}/${page.id}`;

  if (page.id === "home") {
    // index.html is the source — just verify its head matches its own attributes
    const expected = setHead(source, page, url);
    if (expected !== source) {
      fs.writeFileSync("index.html", expected);
      console.log("✓ index.html: head synced with page-home attributes");
    }
  } else {
    const html = setHead(source, page, url).replace(
      "<!DOCTYPE html>",
      "<!DOCTYPE html>\n<!-- Generated by build-pages.js from index.html — edit index.html instead -->"
    );
    fs.writeFileSync(`${page.id}.html`, html);
    console.log(`✓ ${page.id}.html`);
  }

  sitemapEntries.push({ url, priority: page.id === "home" ? "1.0" : page.id === "legal" ? "0.3" : "0.8" });
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapEntries.map((e) => `  <url>
    <loc>${e.url}</loc>
    <lastmod>${today}</lastmod>
    <priority>${e.priority}</priority>
  </url>`).join("\n")}
</urlset>
`;
fs.writeFileSync("sitemap.xml", sitemap);
console.log(`✓ sitemap.xml (${sitemapEntries.length} URLs)`);
